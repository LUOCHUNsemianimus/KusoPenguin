package com.luochun.kusopenguin.registry;

import com.luochun.kusopenguin.KusoPenguin;
import net.minecraft.core.registries.Registries;
import net.minecraft.world.effect.MobEffect;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;

public final class ModEffects {
    private static final DeferredRegister<MobEffect> EFFECTS =
            DeferredRegister.create(Registries.MOB_EFFECT, KusoPenguin.MODID);

    public static final DeferredHolder<MobEffect, MobEffect> PENGUIN =
            EFFECTS.register("penguin", PenguinEffect::new);

    private ModEffects() {
    }

    public static void register(IEventBus modEventBus) {
        EFFECTS.register(modEventBus);
    }
}
